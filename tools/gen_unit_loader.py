#!/usr/bin/env python3
"""Adapts the Microsoft Calculator C# UnitConverterDataLoader data tables to the Avalonia port."""
import pathlib, re

SRC = pathlib.Path('/home/claude/src_ms/src/Calculator.ViewModels/DataLoaders/UnitConverterDataLoader.cs').read_text()
OUT = pathlib.Path('/home/claude/CalculatorAvalonia/src/Calculator.Engine/UnitConversion/UnitConverterDataLoader.cs')

def between(text, start, end, include_start=True):
    i = text.index(start)
    j = text.index(end, i)
    return text[i if include_start else i + len(start):j]

consts = between(SRC, '        #region Unit ID Constants', '        #endregion') + '        #endregion\n'
units = between(SRC, '            // ---- Area ----', '            // Sort units by order and store')
factors = between(SRC, '            var conversionFactors = new Dictionary<ViewMode, Dictionary<int, double>>', '            // Build unit lookup by ID')

def fix(t):
    t = t.replace('ViewMode.', 'ConverterCategory.')
    t = t.replace('Dictionary<ViewMode,', 'Dictionary<ConverterCategory,')
    t = t.replace('MillimeterOfMercury "', 'MillimeterOfMercury"')
    return t

units, factors = fix(units), fix(factors)

# Corrections of the conversion factors copied from Windows Calculator, checked against exact definitions
# (SI, NIST, legal definitions of the US units) by tools/check_units.py and tests/ConverterAccuracyTests.cs.
# The original rounds these: 1 mph = 1.6092 km/h instead of 1.609344, 1 atm = 760.13 mmHg instead of 760, ...
FACTOR_CORRECTIONS = [
    ("{ Energy_ElectronVolt, 0.0000000000000000001602176565 },", "{ Energy_ElectronVolt, 0.0000000000000000001602176634 },"),  # exact since the 2019 SI redefinition
    ("{ Volume_CupUS, 236.588237 },", "{ Volume_CupUS, 236.5882365 },"),                                                       # 1/16 US gallon
    ("{ Speed_Knot, 51.44 },", "{ Speed_Knot, 51.444444444444444444 },"),                                                      # 1852 m / 3600 s
    ("{ Speed_MilesPerHour, 44.7 },", "{ Speed_MilesPerHour, 44.704 },"),                                                      # 1609.344 m / 3600 s
    ("{ Pressure_MillimeterOfMercury, 0.0013155687145324 },", "{ Pressure_MillimeterOfMercury, 0.0013157894736842105 },"),   # 1 atm = 760 mmHg
    ("{ Pressure_PSI, 0.068045961016531 },", "{ Pressure_PSI, 0.06804596390987773 },"),                                         # lbf / in2 / 101325 Pa
]
for old, new in FACTOR_CORRECTIONS:
    assert factors.count(old) == 1, 'factor to correct not found (did the upstream table change?): ' + old
    factors = factors.replace(old, new)

# the 'matches GetConversionData in C++' comment is kept inside 'factors' only partially; fine.
template = '''// Unit and conversion data of the unit converter, adapted from the C# UnitConverterDataLoader of Windows Calculator.
// Original: Copyright (c) Microsoft Corporation. Licensed under the MIT License.
// <auto-generated> by tools/gen_unit_loader.py (data tables copied from the original source). </auto-generated>

using System;
using System.Collections.Generic;
using System.Linq;

namespace Calculator.Engine.UnitConversion;

/// <summary>The unit converter categories. The values are the serialization ids used by Windows Calculator.</summary>
public enum ConverterCategory
{
    Volume = 4,
    Length = 5,
    Weight = 6,
    Temperature = 7,
    Energy = 8,
    Area = 9,
    Speed = 10,
    Time = 11,
    Power = 12,
    Data = 13,
    Pressure = 14,
    Angle = 15,
}

/// <summary>
/// Loads unit converter data and provides conversion data for all unit categories.
/// Display names come from the string provider (keys of the Windows Calculator resources, e.g. "UnitName_Acre").
/// </summary>
public sealed class UnitConverterDataLoader : IConverterDataLoader
{
    private static readonly ConverterCategory[] s_converterModes =
    {
        ConverterCategory.Volume, ConverterCategory.Length, ConverterCategory.Weight,
        ConverterCategory.Temperature, ConverterCategory.Energy, ConverterCategory.Area,
        ConverterCategory.Speed, ConverterCategory.Time, ConverterCategory.Power,
        ConverterCategory.Data, ConverterCategory.Pressure, ConverterCategory.Angle,
    };

    /// <summary>
    /// The categories of this loader, in display order (the currency category, added by <see cref="CurrencyConverterDataLoader"/>,
    /// comes last). Lets the interface build its navigation list without loading all the unit data.
    /// </summary>
    public static IReadOnlyList<ConverterCategory> OrderedCategories => s_converterModes;

    private readonly Func<string, string> _getString;

    // Region-dependent flags (default to US)
    private readonly string _regionCode;

    private List<Category> _categories = new List<Category>();
    private Dictionary<int, List<Unit>> _unitsByCategory = new Dictionary<int, List<Unit>>();
    private Dictionary<int, Dictionary<Unit, ConversionData>> _ratiosByUnit = new Dictionary<int, Dictionary<Unit, ConversionData>>();
    private bool _loaded;

    /// <param name="getString">Returns the localized string for a resource key.</param>
    /// <param name="regionCode">Two letter ISO region code, used to pick default units (US customary / SI, Fahrenheit, ...).</param>
    public UnitConverterDataLoader(Func<string, string> getString, string? regionCode = null)
    {
        _getString = getString;
        _regionCode = string.IsNullOrEmpty(regionCode) ? "US" : regionCode!.ToUpperInvariant();
    }

    /// <summary>Name resource key of each category.</summary>
    private static string CategoryNameKey(ConverterCategory c) => "CategoryName_" + c + "Text";

__CONSTS__
    public void LoadData()
    {
        if (_loaded)
        {
            return;
        }

        _loaded = true;

        // Determine region-dependent flags
        bool useUSCustomaryAndFahrenheit =
            _regionCode == "US" || _regionCode == "FM" || _regionCode == "MH" || _regionCode == "PW";
        bool useUSCustomary = useUSCustomaryAndFahrenheit || _regionCode == "LR";
        bool useSI = !useUSCustomary;
        bool useFahrenheit = useUSCustomaryAndFahrenheit || _regionCode == "BS" || _regionCode == "KY" || _regionCode == "LR";
        bool useWattInsteadOfKilowatt = _regionCode == "GB";
        bool usePyeong = _regionCode == "JP" || _regionCode == "TW" || _regionCode == "KP" || _regionCode == "KR";

        string Loc(string key) => _getString(key.Trim());

        _categories = new List<Category>();
        foreach (ConverterCategory mode in s_converterModes)
        {
            string categoryName = Loc(CategoryNameKey(mode));
            if (string.IsNullOrEmpty(categoryName))
            {
                categoryName = mode.ToString();
            }

            bool supportsNegative = mode == ConverterCategory.Temperature || mode == ConverterCategory.Power || mode == ConverterCategory.Angle;
            _categories.Add(new Category((int)mode, categoryName, supportsNegative));
        }

        // Build units per category
        var unitsByCategory = new Dictionary<int, List<(Unit unit, int order)>>();

        void AddUnit(ConverterCategory mode, int id, string nameKey, string abbrKey, int order,
            bool isSource = false, bool isTarget = false, bool isWhimsical = false)
        {
            int catId = (int)mode;
            if (!unitsByCategory.TryGetValue(catId, out List<(Unit unit, int order)>? list))
            {
                list = new List<(Unit unit, int order)>();
                unitsByCategory[catId] = list;
            }

            list.Add((new Unit(id, Loc(nameKey), Loc(abbrKey), isSource, isTarget, isWhimsical), order));
        }

__UNITS__
        // Sort units by order and store
        _unitsByCategory = new Dictionary<int, List<Unit>>();
        foreach (KeyValuePair<int, List<(Unit unit, int order)>> kvp in unitsByCategory)
        {
            _unitsByCategory[kvp.Key] = kvp.Value.OrderBy(x => x.order).Select(x => x.unit).ToList();
        }

        // Build conversion factors per category
__FACTORS__
        // Build unit lookup by ID
        var allUnitsById = new Dictionary<int, Unit>();
        foreach (KeyValuePair<int, List<Unit>> kvp in _unitsByCategory)
        {
            foreach (Unit unit in kvp.Value)
            {
                allUnitsById[unit.Id] = unit;
            }
        }

        // Build the ratio map: for each unit, compute conversions to all other units in the same category
        _ratiosByUnit = new Dictionary<int, Dictionary<Unit, ConversionData>>();

        foreach (Category cat in _categories)
        {
            var categoryViewMode = (ConverterCategory)cat.Id;

            if (!_unitsByCategory.TryGetValue(cat.Id, out List<Unit>? units) || units.Count == 0)
            {
                continue;
            }

            foreach (Unit sourceUnit in units)
            {
                var entries = new Dictionary<Unit, ConversionData>();

                if (explicitConversions.TryGetValue(sourceUnit.Id, out Dictionary<int, (double ratio, double offset, bool offsetFirst)>? explicitMap))
                {
                    // Temperature: use explicit conversion data
                    foreach (KeyValuePair<int, (double ratio, double offset, bool offsetFirst)> kvp in explicitMap)
                    {
                        if (allUnitsById.TryGetValue(kvp.Key, out Unit targetUnit))
                        {
                            entries[targetUnit] = new ConversionData(kvp.Value.ratio, kvp.Value.offset, kvp.Value.offsetFirst);
                        }
                    }
                }
                else if (conversionFactors.TryGetValue(categoryViewMode, out Dictionary<int, double>? categoryFactors))
                {
                    // Standard factor-based conversion: ratio = sourceFactor / targetFactor
                    if (!categoryFactors.TryGetValue(sourceUnit.Id, out double sourceFactor))
                    {
                        continue;
                    }

                    foreach (Unit targetUnit in units)
                    {
                        if (categoryFactors.TryGetValue(targetUnit.Id, out double targetFactor) && targetFactor > 0)
                        {
                            entries[targetUnit] = new ConversionData(sourceFactor / targetFactor, 0, false);
                        }
                    }
                }

                _ratiosByUnit[sourceUnit.Id] = entries;
            }
        }
    }

    public List<Category> GetOrderedCategories()
    {
        LoadData();
        return new List<Category>(_categories);
    }

    public List<Unit> GetOrderedUnits(Category category)
    {
        LoadData();
        if (_unitsByCategory.TryGetValue(category.Id, out List<Unit>? units))
        {
            return new List<Unit>(units);
        }

        return new List<Unit>();
    }

    public Dictionary<Unit, ConversionData> LoadOrderedRatios(Unit unit)
    {
        LoadData();
        if (_ratiosByUnit.TryGetValue(unit.Id, out Dictionary<Unit, ConversionData>? ratios))
        {
            return new Dictionary<Unit, ConversionData>(ratios);
        }

        return new Dictionary<Unit, ConversionData>();
    }

    public bool SupportsCategory(Category target) => true;
}
'''
out = template.replace('__CONSTS__', consts).replace('__UNITS__', units).replace('__FACTORS__', factors)
OUT.write_text(out)
print(len(out.splitlines()), 'lines')
