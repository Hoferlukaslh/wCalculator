#!/usr/bin/env python3
"""Generate C# command constants / enums / engine string keys from the Microsoft Calculator headers."""
import re, sys, pathlib

SRC = pathlib.Path('/home/claude/src_ms/src/CalcManager')
OUT = pathlib.Path('/home/claude/CalculatorAvalonia/src/Calculator.Engine/CEngine')

# ---------------- CCommand.h -> CCommand.cs ----------------
text = (SRC / 'Header Files/CCommand.h').read_text()
defs = []
for line in text.splitlines():
    m = re.match(r'#define\s+(\w+)\s+(\w+)\s*(//.*)?$', line)
    if m:
        defs.append((m.group(1), m.group(2)))
lines = ['// <auto-generated> by tools/gen_commands.py from CCommand.h. Do not edit. </auto-generated>',
         '// Original: Copyright (c) Microsoft Corporation. Licensed under the MIT License.',
         '', 'namespace Calculator.Engine;', '',
         '/// <summary>Command ids that can be passed to the calculator engine (port of CCommand.h).</summary>',
         'internal static class CCommand', '{']
for n, v in defs:
    lines.append(f'    public const int {n} = {v};')
lines.append('}')
(OUT / 'CCommand.cs').write_text('\n'.join(lines) + '\n')

# ---------------- Command.h -> Command.cs ----------------
text = (SRC / 'Command.h').read_text()
def grab_enum(ns, name):
    m = re.search(r'namespace\s+%s\s*\{(.*?)\n\}' % ns, text, re.S)
    body = m.group(1)
    m2 = re.search(r'enum class %s\s*\{(.*?)\};' % name, body, re.S)
    return m2.group(1)

def convert_members(body):
    out = []
    for line in body.splitlines():
        s = line.strip()
        if not s:
            continue
        if s.startswith('//'):
            out.append('    ' + s)
            continue
        out.append('    ' + s)
    return '\n'.join(out)

calc = grab_enum('CalculationManager', 'Command')
unit = grab_enum('UnitConversionManager', 'Command')
res = ['// <auto-generated> by tools/gen_commands.py from Command.h. Do not edit. </auto-generated>',
       '// Original: Copyright (c) Microsoft Corporation. Licensed under the MIT License.',
       '', 'namespace Calculator.Engine;', '',
       'public enum CommandType', '{', '    UnaryCommand,', '    BinaryCommand,', '    OperandCommand,', '    Parentheses,', '}', '',
       '/// <summary>Commands understood by <see cref="CalculatorManager"/> (port of CalculationManager::Command).</summary>',
       'public enum Command', '{', convert_members(calc), '}', '',
       '/// <summary>Commands understood by the unit converter (port of UnitConversionManager::Command).</summary>',
       'public enum UnitConversionCommand', '{', convert_members(unit), '}']
(OUT / 'Command.cs').write_text('\n'.join(res) + '\n')

# ---------------- EngineStrings.h -> EngineStrings.cs ----------------
text = (SRC / 'Header Files/EngineStrings.h').read_text()
consts = re.findall(r'inline constexpr auto (SIDS_\w+) = L"([^"]*)";', text)
errs = re.findall(r'inline constexpr auto ((?:IDS_|CSTRINGSENGMAX)\w*) = ([^;]+);', text)
sids_list = re.search(r'g_sids = \{(.*?)\};', text, re.S).group(1)
sids_names = re.findall(r'(SIDS_\w+)', sids_list)
res = ['// <auto-generated> by tools/gen_commands.py from EngineStrings.h. Do not edit. </auto-generated>',
       '// Original: Copyright (c) Microsoft Corporation. Licensed under the MIT License.',
       '', 'namespace Calculator.Engine;', '',
       'internal static class EngineStrings', '{']
for n, v in errs:
    v = v.replace('IDS_ERRORS_FIRST', 'IDS_ERRORS_FIRST')
    res.append(f'    public const int {n} = {v.strip()};')
res.append('')
for n, v in consts:
    res.append(f'    public const string {n} = "{v}";')
res.append('')
res.append('    /// <summary>Resource keys loaded into memory for the engine to use (g_sids).</summary>')
res.append('    public static readonly string[] AllKeys =')
res.append('    {')
for n in sids_names:
    res.append(f'        {n},')
res.append('    };')
res.append('}')
(OUT / 'EngineStrings.cs').write_text('\n'.join(res) + '\n')
print(len(defs), 'ccommand defs;', len(consts), 'sids;', len(sids_names), 'keys;', len(errs), 'ids')
