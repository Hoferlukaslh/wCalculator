import re, sys
src = open(sys.argv[1], encoding='utf-8-sig').read()
pat = re.compile(r'inline const NUMBER init_(\w+)\s*=\s*\{\s*(-?\d+)\s*,\s*(\d+)\s*,\s*(-?\d+)\s*,\s*\{([^}]*)\}\s*\};', re.S)
items = []
for m in pat.finditer(src):
    name, sign, cd, exp, mant = m.groups()
    digits = [int(x) for x in re.findall(r'-?\d+', mant)]
    assert len(digits) == int(cd), (name, len(digits), cd)
    items.append((name, int(sign), int(cd), int(exp), digits))
out = []
out.append("// <auto-generated> Converted from ratconst.h (Microsoft Calculator, MIT License) by tools/gen_consts.py </auto-generated>")
out.append("namespace Calculator.Engine.Ratpak;\n")
out.append("internal static partial class RatPak\n{")
out.append("    private static Number MakeConst(int sign, int exp, params uint[] mant)")
out.append("    {")
out.append("        var n = new Number(mant.Length) { Sign = sign, Cdigit = mant.Length, Exp = exp };")
out.append("        System.Array.Copy(mant, n.Mant, mant.Length);")
out.append("        return n;")
out.append("    }\n")
for name, sign, cd, exp, digits in items:
    out.append(f"    private static Number init_{name}() => MakeConst({sign}, {exp}, {', '.join(str(d)+'u' for d in digits)});")
out.append("")
# rat names = those with init_p_
rats = [n[len('p_'):] for (n, *_ ) in items if n.startswith('p_')]
nums = [n[0] for n in items if not n[0].startswith('p_') and not n[0].startswith('q_')]
out.append("    private static void _readconstants()")
out.append("    {")
for n in nums:
    out.append(f"        {n} = init_{n}();")
for r in rats:
    out.append(f"        {r} = new Rat {{ Pp = init_p_{r}(), Pq = init_q_{r}() }};")
out.append("    }")
out.append("}")
open(sys.argv[2], 'w').write("\n".join(out) + "\n")
print(len(items), "numbers;", rats, nums)
